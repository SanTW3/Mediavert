// Сравнение версий вида 2.10.3: -1, 0, 1
function compareVersions(a, b) {
  const pa = String(a).split('.').map(Number);
  const pb = String(b).split('.').map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d) return d > 0 ? 1 : -1;
  }
  return 0;
}

// Изменения новее since (не включая) и не новее until (включая)
function changesBetween(since, until) {
  return CHANGELOG.filter((e) => compareVersions(e.version, until) <= 0 && (!since || compareVersions(e.version, since) > 0));
}

